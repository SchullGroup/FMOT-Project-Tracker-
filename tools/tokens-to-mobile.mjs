// pnpm tokens: writes apps/mobile/src/theme/tokens.ts from the Penpot token catalogue (tools/penpot-ds-tokens.json),
// the same catalogue as the web theme. Every token of the Light theme (core, semantic, component) is resolved to a
// literal; the Large text theme's font sizes go in largeText. Colours, sizes and type on the phone come only from here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(readFileSync(join(root, 'tools/penpot-ds-tokens.json'), 'utf8'));
const outPath = join(root, 'apps/mobile/src/theme/tokens.ts');

const setsOf = (theme) => catalogue.themes.find((t) => t.name === theme).sets;
const tokensFor = (sets) => {
  const map = new Map();
  for (const name of sets) for (const t of catalogue.sets.find((s) => s.name === name).tokens) map.set(t.name, t);
  return map;
};

// Follow {references} (whole values, or inside a typography object) down to literals.
function resolver(tokens) {
  const resolve = (value, seen) => {
    if (typeof value === 'string') {
      const ref = /^\{([^}]+)\}$/.exec(value);
      if (!ref) return value;
      if (seen.has(ref[1])) throw new Error(`Token reference loop at ${ref[1]}`);
      const token = tokens.get(ref[1]);
      if (!token) throw new Error(`Unknown token ${ref[1]}`);
      return resolve(token.value, new Set([...seen, ref[1]]));
    }
    if (Array.isArray(value)) return value.map((v) => resolve(v, seen));
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, seen)]));
    return value;
  };
  return (name) => resolve(tokens.get(name).value, new Set([name]));
}

// Numbers stay numbers ("16" -> 16); a one-item font family list becomes its name.
const literal = (v) => {
  if (Array.isArray(v)) {
    const flat = v.flat(Infinity);
    if (flat.length === 1 && typeof flat[0] === 'string') return flat[0];
  }
  if (typeof v === 'string' && /^-?\d+(\.\d+)?$/.test(v)) return Number(v);
  if (v && typeof v === 'object' && !Array.isArray(v)) return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, literal(x)]));
  return v;
};

const light = tokensFor(setsOf('Light'));
const large = tokensFor(setsOf('Large text'));
const resolveLight = resolver(light);
const resolveLarge = resolver(large);

const all = Object.fromEntries([...light.keys()].sort().map((name) => [name, literal(resolveLight(name))]));
const largeText = Object.fromEntries(
  catalogue.sets.find((s) => s.name === 'semantic-large-text').tokens.map((t) => [t.name, literal(resolveLarge(t.name))]),
);

const body = `// Generated by tools/tokens-to-mobile.mjs from tools/penpot-ds-tokens.json (saved ${catalogue.saved}). Do not edit:
// change the tokens in Penpot, export them, and run \`pnpm tokens\`.
/* eslint-disable */
export const tokens = ${JSON.stringify(all, null, 2)} as const;

/** The Large text theme: the font sizes it changes (25 percent larger). */
export const largeText = ${JSON.stringify(largeText, null, 2)} as const;

export type TokenName = keyof typeof tokens;
`;
writeFileSync(outPath, body);
console.log(`Wrote ${Object.keys(all).length} tokens and ${Object.keys(largeText).length} large-text sizes to ${outPath}`);
