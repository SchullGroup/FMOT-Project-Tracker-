// pnpm tokens: regenerates the @theme block in apps/web/src/app/globals.css from the Penpot token catalogue
// (tools/penpot-ds-tokens.json), keeping the variable names the web components use. Only the Light theme's sets
// (core, semantic, component) are read; Large text is the html[data-text="large"] rule in globals.css.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(readFileSync(join(root, 'tools/penpot-ds-tokens.json'), 'utf8'));
const cssPath = join(root, 'apps/web/src/app/globals.css');

const tokens = new Map();
for (const set of catalogue.sets.filter((s) => ['core', 'semantic', 'component'].includes(s.name))) {
  for (const t of set.tokens) tokens.set(t.name, t);
}

// Follow {references} down to a literal value.
function resolve(name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Token reference loop at ${name}`);
  seen.add(name);
  const token = tokens.get(name);
  if (!token) throw new Error(`Unknown token ${name}`);
  const value = token.value;
  if (typeof value === 'string') {
    const ref = /^\{([^}]+)\}$/.exec(value);
    if (ref) return resolve(ref[1], seen);
  }
  return value;
}

// CSS variable (as the components use it) -> token.
const COLOURS = {
  'brand-900': 'color.navy.900',
  'brand-800': 'color.navy.800',
  'brand-700': 'color.navy.700',
  'brand-100': 'color.navy.100',
  'brand-50': 'color.navy.50',
  accent: 'color.brand.secondary',
  surface: 'color.surface.raised',
  canvas: 'color.grey.50',
  ink: 'color.text.primary',
  'ink-muted': 'color.text.tertiary',
  line: 'color.border.default',
  'line-strong': 'color.border.strong',
  'status-operational': 'color.status.operational.line',
  'status-construction': 'color.status.under-construction.line',
  'status-planned': 'color.status.planned.line',
  'status-stalled': 'color.status.stalled.line',
  'status-draft': 'color.status.draft.line',
  danger: 'color.text.error',
  focus: 'color.focus.ring',
};
const RADII = { sm: 'radius.4', md: 'radius.8', lg: 'radius.16' };

const family = resolve('font.family.ui');
const lines = [
  `  --font-sans: ${[...(Array.isArray(family) ? family : [family])].map((f) => `'${f} Variable'`).join(', ')}, 'Source Sans Pro', system-ui, sans-serif;`,
  '',
  ...Object.entries(COLOURS).map(([name, token]) => `  --color-${name}: ${String(resolve(token)).toLowerCase()}; /* ${token} */`),
  '',
  ...Object.entries(RADII).map(([name, token]) => `  --radius-${name}: ${resolve(token)}px; /* ${token} */`),
];

const css = readFileSync(cssPath, 'utf8');
const start = css.indexOf('@theme {');
const end = css.indexOf('\n}', start);
if (start < 0 || end < 0) throw new Error('No @theme block in globals.css');
const block = `@theme {\n  /* Generated by tools/tokens-to-css.mjs (pnpm tokens) from tools/penpot-ds-tokens.json; do not edit by hand. */\n${lines.join('\n')}`;
writeFileSync(cssPath, css.slice(0, start) + block + css.slice(end));
console.log(`globals.css: ${Object.keys(COLOURS).length} colours and ${Object.keys(RADII).length} radii from ${tokens.size} tokens`);
